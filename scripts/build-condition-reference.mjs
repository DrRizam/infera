// One-off converter — parses Reference/Condition Reference.md (the user's
// master PT-diagnosis taxonomy, gitignored raw source) into a flat JS data
// file the app can actually import and search. Not part of the build;
// rerun manually if the source doc changes:
//   node scripts/build-condition-reference.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = join(__dirname, "..", "Reference", "Condition Reference.md");
const OUT = join(__dirname, "..", "src", "data", "conditionReference.js");

const lines = readFileSync(SRC, "utf-8").split("\n");

const entries = [];
let part = null;
let section = null;

for (const raw of lines) {
  const line = raw.trim();
  const partMatch = line.match(/^##\s+(PART.+)$/);
  if (partMatch) {
    part = partMatch[1].trim();
    section = null;
    continue;
  }
  const sectionMatch = line.match(/^###\s+(.+)$/);
  if (sectionMatch) {
    section = sectionMatch[1].trim();
    continue;
  }
  const itemMatch = line.match(/^-\s+(.+)$/);
  if (itemMatch && part) {
    const redFlag = itemMatch[1].includes("🚩");
    const comorbidity = itemMatch[1].includes("⚕️");
    const name = itemMatch[1]
      .replace(/🚩/g, "")
      .replace(/⚕️/g, "")
      .trim();
    entries.push({ part, section: section || part, name, redFlag, comorbidity });
  }
}

const out = `// Auto-generated by scripts/build-condition-reference.mjs — do not hand-edit.
// Source: Reference/Condition Reference.md (gitignored, the user's master
// PT-diagnosis taxonomy). Rerun the script if the source doc changes.
export const CONDITION_REFERENCE = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(OUT, out);
console.log(`wrote ${entries.length} entries across ${new Set(entries.map((e) => e.part)).size} parts to ${OUT}`);
